export function buildFeedback(result, { gender = 'm', name = '' } = {}) {
  const g = (m, f) => (gender === 'f' ? f : m);
  const T = texts(g);
  const good = [], improve = [];
  for (const id of ORDER) {
    const m = result.metrics[id];
    // 'ok' = בסדר: לא משבחים ולא מעירים. 'na' = לא נמדד בביטחון.
    if (!m || m.status === 'na' || m.status === 'ok') continue;
    if (m.status === 'good') good.push({ id, text: T[id].good.say, keep: T[id].good.keep });
    else if (T[id][m.status]) improve.push({ id, text: T[id][m.status] });
  }

  const keep = good.length ? good[0].keep : g('תמשיך להתאמן, כל בעיטה משפרת', 'תמשיכי להתאמן, כל בעיטה משפרת');
  const { good: gc, total } = result.score;
  let opener;
  const who = name ? `, ${name}` : '';
  if (total && gc === total) opener = `בעיטה מצוינת${who}!`;
  else if (total && gc / total >= 0.5) opener = `בעיטה טובה${who}!`;
  else opener = `${name ? name + ', ' : ''}${g('בוא נשפר', 'בואי נשפר')} כמה דברים.`;

  // בהקראה: עד שתי נקודות טובות ושתי נקודות לשיפור, כדי לא להעמיס
  const parts = [opener];
  if (good.length) parts.push('מה היה טוב: ' + good.slice(0, 2).map((x) => x.text).join('. וגם, ') + '.');
  if (improve.length) parts.push('מה לשפר: ' + improve.slice(0, 2).map((x) => x.text).join('. וגם, ') + '.');
  parts.push('על מה לשמור: ' + keep + '.');

  return { opener, good, improve, keep, speech: parts.join(' ') };
}

export function errorMessage(error, gender = 'm') {
  const g = (m, f) => (gender === 'f' ? f : m);
  switch (error) {
    case 'few-frames':
      return g('לא הצלחתי לראות את הילד מספיק טוב בסרטון. נסה שוב, כשכל הגוף בתמונה', 'לא הצלחתי לראות את הילד מספיק טוב בסרטון. נסי שוב, כשכל הגוף בתמונה');
    case 'no-ball':
      return g('לא מצאתי את הכדור. הקש על הכדור בתמונה', 'לא מצאתי את הכדור. הקישי על הכדור בתמונה');
    case 'no-contact':
      return g('לא זיהיתי את רגע הבעיטה. ודא שהכדור והילד בתמונה לאורך כל הבעיטה ונסה שוב', 'לא זיהיתי את רגע הבעיטה. ודאי שהכדור והילד בתמונה לאורך כל הבעיטה ונסי שוב');
    default:
      return 'משהו השתבש בניתוח. ננסה שוב';
  }
}
